package models;

import interfaces.Observer;

/**
 *
 * @author macbook
 */
public abstract class Person implements Observer {

    protected String name;
    protected String email;
    protected String phone;

    public Person(String name, String email, String phone) {
        this.name = name;
        this.email = email;
        this.phone = phone;
    }
}
